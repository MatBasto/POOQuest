-- POOQuest Adventure v5
-- Estrellas funcionales por nivel. Ejecutar una sola vez en Supabase SQL Editor.
-- No elimina usuarios, XP, progreso, intentos ni recompensas existentes.

create table if not exists public.level_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  best_stars int not null default 1 check (best_stars between 1 and 3),
  last_stars int not null default 1 check (last_stars between 1 and 3),
  best_errors int not null default 0,
  best_hints int not null default 0,
  plays int not null default 0,
  updated_at timestamptz not null default now(),
  unique(user_id, level_id)
);

alter table public.level_scores enable row level security;
grant select on table public.level_scores to authenticated;

drop policy if exists "own level scores read" on public.level_scores;
create policy "own level scores read" on public.level_scores
for select using (auth.uid() = user_id);

drop policy if exists "own level scores insert" on public.level_scores;
create policy "own level scores insert" on public.level_scores
for insert with check (auth.uid() = user_id);

drop policy if exists "own level scores update" on public.level_scores;
create policy "own level scores update" on public.level_scores
for update using (auth.uid() = user_id);

create or replace function public.record_level_score(
  p_level_id bigint,
  p_errors int default 0,
  p_hints int default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  u uuid := auth.uid();
  calculated int;
  previous_best int;
  final_best int;
begin
  if u is null then raise exception 'Sesión requerida'; end if;
  if not exists(select 1 from public.levels where id = p_level_id) then
    raise exception 'Nivel inválido';
  end if;

  calculated := case
    when greatest(coalesce(p_errors,0),0) = 0 and greatest(coalesce(p_hints,0),0) = 0 then 3
    when greatest(coalesce(p_errors,0),0) <= 2 and greatest(coalesce(p_hints,0),0) <= 1 then 2
    else 1
  end;

  select best_stars into previous_best
  from public.level_scores
  where user_id = u and level_id = p_level_id;

  insert into public.level_scores(user_id,level_id,best_stars,last_stars,best_errors,best_hints,plays,updated_at)
  values(u,p_level_id,calculated,calculated,greatest(coalesce(p_errors,0),0),greatest(coalesce(p_hints,0),0),1,now())
  on conflict(user_id,level_id) do update set
    best_stars = greatest(public.level_scores.best_stars, excluded.last_stars),
    last_stars = excluded.last_stars,
    best_errors = case
      when excluded.last_stars > public.level_scores.best_stars then excluded.best_errors
      when excluded.last_stars = public.level_scores.best_stars and (excluded.best_errors + excluded.best_hints) < (public.level_scores.best_errors + public.level_scores.best_hints) then excluded.best_errors
      else public.level_scores.best_errors
    end,
    best_hints = case
      when excluded.last_stars > public.level_scores.best_stars then excluded.best_hints
      when excluded.last_stars = public.level_scores.best_stars and (excluded.best_errors + excluded.best_hints) < (public.level_scores.best_errors + public.level_scores.best_hints) then excluded.best_hints
      else public.level_scores.best_hints
    end,
    plays = public.level_scores.plays + 1,
    updated_at = now();

  select best_stars into final_best
  from public.level_scores
  where user_id = u and level_id = p_level_id;

  return jsonb_build_object(
    'stars', calculated,
    'best_stars', final_best,
    'improved', coalesce(previous_best,0) < final_best
  );
end $$;

grant execute on function public.record_level_score(bigint,int,int) to authenticated;

-- Inicializa una puntuación para niveles que ya estaban completados.
-- Los errores históricos se toman de intentos incorrectos de la misión interactiva.
-- Las pistas anteriores a v5 no podían registrarse, por eso se consideran 0 solo en este backfill.
insert into public.level_scores(user_id, level_id, best_stars, last_stars, best_errors, best_hints, plays, updated_at)
select
  lp.user_id,
  lp.level_id,
  case when x.errors = 0 then 3 when x.errors <= 2 then 2 else 1 end,
  case when x.errors = 0 then 3 when x.errors <= 2 then 2 else 1 end,
  x.errors,
  0,
  1,
  now()
from public.level_progress lp
cross join lateral (
  select
    (select count(*)::int
       from public.activity_attempts aa
       join public.activities a on a.id = aa.activity_id
      where aa.user_id = lp.user_id and a.level_id = lp.level_id and aa.is_correct = false)
    as errors
) x
where lp.status = 'completed'
on conflict(user_id,level_id) do nothing;
