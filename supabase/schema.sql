create or replace function public.record_level_score(p_level_id bigint,p_errors int default 0,p_hints int default 0)
returns jsonb language plpgsql security definer set search_path=public as $$
declare u uuid:=auth.uid(); calculated int; previous_best int; final_best int;
begin
  if u is null then raise exception 'Sesión requerida'; end if;
  if not exists(select 1 from public.levels where id=p_level_id) then raise exception 'Nivel inválido'; end if;
  calculated := case when greatest(coalesce(p_errors,0),0)=0 and greatest(coalesce(p_hints,0),0)=0 then 3 when greatest(coalesce(p_errors,0),0)<=2 and greatest(coalesce(p_hints,0),0)<=1 then 2 else 1 end;
  select best_stars into previous_best from public.level_scores where user_id=u and level_id=p_level_id;
  insert into public.level_scores(user_id,level_id,best_stars,last_stars,best_errors,best_hints,plays,updated_at)
  values(u,p_level_id,calculated,calculated,greatest(coalesce(p_errors,0),0),greatest(coalesce(p_hints,0),0),1,now())
  on conflict(user_id,level_id) do update set
    best_stars=greatest(public.level_scores.best_stars,excluded.last_stars),
    last_stars=excluded.last_stars,
    best_errors=case when excluded.last_stars>public.level_scores.best_stars then excluded.best_errors when excluded.last_stars=public.level_scores.best_stars and (excluded.best_errors+excluded.best_hints)<(public.level_scores.best_errors+public.level_scores.best_hints) then excluded.best_errors else public.level_scores.best_errors end,
    best_hints=case when excluded.last_stars>public.level_scores.best_stars then excluded.best_hints when excluded.last_stars=public.level_scores.best_stars and (excluded.best_errors+excluded.best_hints)<(public.level_scores.best_errors+public.level_scores.best_hints) then excluded.best_hints else public.level_scores.best_hints end,
    plays=public.level_scores.plays+1,updated_at=now();
  select best_stars into final_best from public.level_scores where user_id=u and level_id=p_level_id;
  return jsonb_build_object('stars',calculated,'best_stars',final_best,'improved',coalesce(previous_best,0)<final_best);
end $$;
grant execute on function public.record_level_score(bigint,int,int) to authenticated;
