create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Estudiante',
  xp integer not null default 0 check (xp >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.modules (
  id bigint generated by default as identity primary key,
  slug text unique not null, name text not null, description text not null,
  icon text not null default '◈', theme text not null default 'blue', sort_order int not null
);
create table if not exists public.levels (
  id bigint generated by default as identity primary key,
  module_id bigint not null references public.modules(id) on delete cascade,
  slug text unique not null, name text not null, description text not null,
  sort_order int not null, required_xp int not null default 0, xp_reward int not null default 20,
  unique(module_id, sort_order)
);
create table if not exists public.contents (
  id bigint generated by default as identity primary key,
  level_id bigint not null references public.levels(id) on delete cascade,
  title text not null, body text not null, code_example text, visual_type text, sort_order int not null default 1
);
create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  level_id bigint not null references public.levels(id) on delete cascade,
  question text not null, feedback_correct text not null, feedback_incorrect text not null, xp_reward int not null default 10
);
create table if not exists public.activity_options (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.activities(id) on delete cascade,
  option_text text not null, is_correct boolean not null default false, sort_order int not null default 1
);
create table if not exists public.activity_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  activity_id bigint not null references public.activities(id) on delete cascade,
  selected_option_id bigint references public.activity_options(id) on delete set null,
  is_correct boolean not null, created_at timestamptz not null default now()
);
create table if not exists public.programming_challenges (
  id bigint generated by default as identity primary key,
  level_id bigint not null references public.levels(id) on delete cascade,
  title text not null, statement text not null, starter_code text not null, expected_output text not null,
  xp_reward int not null default 20
);
create table if not exists public.code_executions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  challenge_id bigint not null references public.programming_challenges(id) on delete cascade,
  code text not null, output text, status text, passed boolean not null default false, created_at timestamptz not null default now()
);
create table if not exists public.level_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  percentage int not null default 0 check (percentage between 0 and 100),
  status text not null default 'in_progress' check(status in ('in_progress','completed')),
  started_at timestamptz not null default now(), completed_at timestamptz, updated_at timestamptz not null default now(),
  unique(user_id,level_id)
);
create table if not exists public.rewards (
  id bigint generated by default as identity primary key,
  slug text unique not null, name text not null, description text not null, icon text not null, xp_threshold int not null
);
create table if not exists public.user_rewards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  reward_id bigint not null references public.rewards(id) on delete cascade,
  earned_at timestamptz not null default now(), unique(user_id,reward_id)
);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,name) values(new.id,coalesce(new.raw_user_meta_data->>'full_name',split_part(new.email,'@',1))) on conflict(id) do nothing; return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.award_threshold_rewards() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.user_rewards(user_id,reward_id) select new.id,r.id from public.rewards r where r.xp_threshold<=new.xp on conflict(user_id,reward_id) do nothing; return new; end $$;
drop trigger if exists on_profile_xp_updated on public.profiles;
create trigger on_profile_xp_updated after update of xp on public.profiles for each row execute function public.award_threshold_rewards();

create or replace function public.refresh_level_progress(p_user uuid,p_level bigint) returns void language plpgsql security definer set search_path=public as $$
declare total_items int; done_items int; pct int; old_status text; reward_xp int;
begin
  select (select count(*) from activities where level_id=p_level)+(select count(*) from programming_challenges where level_id=p_level) into total_items;
  select (select count(distinct a.activity_id) from activity_attempts a join activities x on x.id=a.activity_id where a.user_id=p_user and x.level_id=p_level and a.is_correct)
       + (select count(distinct e.challenge_id) from code_executions e join programming_challenges c on c.id=e.challenge_id where e.user_id=p_user and c.level_id=p_level and e.passed) into done_items;
  pct := case when total_items=0 then 0 else least(100,round(done_items::numeric*100/total_items)::int) end;
  select status into old_status from level_progress where user_id=p_user and level_id=p_level;
  insert into level_progress(user_id,level_id,percentage,status,completed_at,updated_at)
    values(p_user,p_level,pct,case when pct=100 then 'completed' else 'in_progress' end,case when pct=100 then now() else null end,now())
  on conflict(user_id,level_id) do update set percentage=excluded.percentage,status=excluded.status,completed_at=coalesce(level_progress.completed_at,excluded.completed_at),updated_at=now();
  if pct=100 and coalesce(old_status,'')<>'completed' then
    select xp_reward into reward_xp from levels where id=p_level;
    update profiles set xp=xp+coalesce(reward_xp,0),updated_at=now() where id=p_user;
  end if;
end $$;

create or replace function public.submit_activity(p_activity_id bigint,p_option_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare u uuid:=auth.uid(); correct boolean; already boolean; lvl bigint; xp_gain int; f_ok text; f_bad text;
begin
  if u is null then raise exception 'Sesión requerida'; end if;
  select ao.is_correct,a.level_id,a.xp_reward,a.feedback_correct,a.feedback_incorrect into correct,lvl,xp_gain,f_ok,f_bad from activity_options ao join activities a on a.id=ao.activity_id where ao.id=p_option_id and ao.activity_id=p_activity_id;
  if correct is null then raise exception 'Opción inválida'; end if;
  select exists(select 1 from activity_attempts where user_id=u and activity_id=p_activity_id and is_correct) into already;
  insert into activity_attempts(user_id,activity_id,selected_option_id,is_correct) values(u,p_activity_id,p_option_id,correct);
  if correct and not already then update profiles set xp=xp+xp_gain,updated_at=now() where id=u; end if;
  perform refresh_level_progress(u,lvl);
  return jsonb_build_object('correct',correct,'feedback',case when correct then f_ok else f_bad end,'xp_awarded',case when correct and not already then xp_gain else 0 end);
end $$;

create or replace function public.record_code_result(p_challenge_id bigint,p_code text,p_output text,p_status text,p_passed boolean)
returns void language plpgsql security definer set search_path=public as $$
declare u uuid:=auth.uid(); already boolean; lvl bigint; xp_gain int;
begin
  if u is null then raise exception 'Sesión requerida'; end if;
  select level_id,xp_reward into lvl,xp_gain from programming_challenges where id=p_challenge_id;
  select exists(select 1 from code_executions where user_id=u and challenge_id=p_challenge_id and passed) into already;
  insert into code_executions(user_id,challenge_id,code,output,status,passed) values(u,p_challenge_id,p_code,p_output,p_status,p_passed);
  if p_passed and not already then update profiles set xp=xp+xp_gain,updated_at=now() where id=u; end if;
  perform refresh_level_progress(u,lvl);
end $$;

