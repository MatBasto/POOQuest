create table if not exists public.level_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  level_id bigint not null references public.levels(id) on delete cascade,
  best_stars int not null default 1 check (best_stars between 1 and 3),
  last_stars int not null default 1 check (last_stars between 1 and 3),
  best_errors int not null default 0,
  best_hints int not null default 0,
  plays int not null default 0,
  updated_at timestamptz not null default now(),
  unique(user_id, level_id)
);
